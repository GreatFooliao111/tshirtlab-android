    val allItems: List<DesignItem> = styles + techniques + presets

    fun getItemById(id: String): DesignItem? {
        return allItems.find { it.id == id }
    }

    fun searchItems(query: String, filterType: ItemType?): List<DesignItem> {
        val q = query.trim().lowercase()
        return allItems.filter { item ->
            val matchesFilter = (filterType == null || item.type == filterType)
            if (q.isEmpty()) {
                matchesFilter
            } else {
                matchesFilter && (
                    item.nameFa.lowercase().contains(q) ||
                    item.nameEn.lowercase().contains(q) ||
                    item.taglineFa.lowercase().contains(q) ||
                    item.searchKeywords.any { it.lowercase().contains(q) }
                )
            }
        }
    }
